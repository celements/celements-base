package com.celements.globalredirect;

public class GlobalRedirectPreconditionException extends Exception {

  private static final long serialVersionUID = 1L;

  public GlobalRedirectPreconditionException() {
    super();
  }

  public GlobalRedirectPreconditionException(String message) {
    super(message);
  }

  public GlobalRedirectPreconditionException(String message, Throwable cause) {
    super(message, cause);
  }

  public GlobalRedirectPreconditionException(Throwable cause) {
    super(cause);
  }

}
